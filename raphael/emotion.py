"""
Настрій відповіді. Модель ставить на початку відповіді тег [EMO:назва], озвучка
його вирізає (вголос не звучить) і передає тілу разом із реченням: маска, поза,
ефекти й підпис у вікні мови. Згодом за ним мінятиметься й інтонація голосу.
Без залежностей: його беруть і llm (щоб тег не став дією), і tts.
"""
import re

# Назва → як її назвати по-людськи (у вікні мови тіла пише сам оверлей)
EMOTIONS = {
    "smug": "самовдоволена",      # за замовчуванням: її звичний стан
    "happy": "весела",
    "laugh": "регоче",
    "tease": "дражнить",
    "sly": "хитрує",
    "bored": "нудьгує",
    "angry": "зла",
    "shocked": "в шоці",
    "sad": "сумна",
}

# [EMO:happy], [emo: Happy], [EMOTION:happy]
EMO_RE = re.compile(r"\[\s*EMO(?:TION)?\s*:\s*([A-Za-z_]+)\s*\]", re.IGNORECASE)


def take(text: str):
    """→ (емоція або None, текст без тегів). Невідома назва вирізається, але не діє."""
    found = None
    for m in EMO_RE.finditer(text or ""):
        name = m.group(1).lower()
        if found is None and name in EMOTIONS:
            found = name
    return found, EMO_RE.sub("", text or "").strip()


